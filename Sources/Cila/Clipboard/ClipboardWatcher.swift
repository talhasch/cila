import AppKit

/// Polls the general pasteboard and reports copies worth improving.
@MainActor
final class ClipboardWatcher {
    /// Marker added to text Cila copies itself, so it isn't offered again.
    static let ownType = NSPasteboard.PasteboardType("com.talhabugrabulut.cila.own")

    /// Markers used by password managers and other apps (see nspasteboard.org).
    private static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    var onCopy: ((String) -> Void)?

    private let pasteboard = NSPasteboard.general
    private var changeCount = 0
    private var lastText: String?
    private var timer: Timer?

    func start() {
        guard timer == nil else { return }
        changeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func poll() {
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount

        let types = Set(pasteboard.types ?? [])
        // Never read concealed content (passwords) at all.
        guard types.isDisjoint(with: Self.privateTypes) else { return }
        guard let text = pasteboard.string(forType: .string) else { return }

        let isRepeat = text == lastText
        lastText = text
        // NSApp is only active while one of Cila's own windows is focused
        // (the panel never activates it), e.g. copying inside the composer.
        guard !isRepeat,
              !NSApp.isActive,
              !types.contains(Self.ownType),
              !types.contains(.fileURL),
              !AppState.shared.isPaused
        else { return }

        guard !TextFilter.shouldIgnore(text) else { return }
        onCopy?(text)
    }
}
